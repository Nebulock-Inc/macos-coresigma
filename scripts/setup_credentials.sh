#!/bin/bash
#
# coreSigma Credential Setup
# Sets up Elasticsearch/Kibana credentials using macOS Keychain
#
# Usage:
#   ./scripts/setup_credentials.sh              # Interactive setup (Keychain only)
#   ./scripts/setup_credentials.sh --sync-docker # Setup password for Docker + Keychain
#   ./scripts/setup_credentials.sh --api-key    # Create API key (recommended for production)
#   ./scripts/setup_credentials.sh --test       # Test current authentication
#

set -e

KEYCHAIN_SERVICE="coreSigma-Elasticsearch"
ES_URL="${ES_URL:-http://localhost:9200}"
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="$PROJECT_DIR/.env"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

print_header() {
    echo ""
    echo -e "${BLUE}═══════════════════════════════════════════════════════════${NC}"
    echo -e "${BLUE}  coreSigma Credential Setup${NC}"
    echo -e "${BLUE}═══════════════════════════════════════════════════════════${NC}"
    echo ""
}

print_success() {
    echo -e "${GREEN}✓${NC} $1"
}

print_error() {
    echo -e "${RED}✗${NC} $1"
}

print_info() {
    echo -e "${YELLOW}ℹ${NC} $1"
}

# Check if credentials already exist
check_existing() {
    echo "Checking for existing credentials..."
    
    # Check keychain
    if security find-generic-password -s "$KEYCHAIN_SERVICE" -a "elastic" -w &>/dev/null; then
        print_success "Found credentials in macOS Keychain"
        return 0
    fi
    
    # Check environment
    if [[ -n "$ES_API_KEY" ]]; then
        print_success "Found ES_API_KEY in environment"
        return 0
    fi
    
    if [[ -n "$ES_USER" && -n "$ES_PASSWORD" ]]; then
        print_success "Found ES_USER/ES_PASSWORD in environment"
        return 0
    fi
    
    # Check config file
    if [[ -f "$HOME/.coresigma/config.yml" ]]; then
        print_success "Found config file at ~/.coresigma/config.yml"
        return 0
    fi
    
    print_info "No existing credentials found"
    return 1
}

# Store password in keychain
store_in_keychain() {
    local username="${1:-elastic}"
    local password="$2"

    # Over stdin, never argv (which `ps` shows): auth.py replaces the entry without the password on any argv
    printf '%s\n' "$password" | python3 "$PROJECT_DIR/collectors/auth.py" store --username "$username"
}

# Interactive password setup
setup_password() {
    echo ""
    echo "Setting up password authentication..."
    echo ""
    
    read -r -p "Username [elastic]: " username
    username="${username:-elastic}"
    
    read -r -sp "Password: " password
    echo ""
    
    if [[ -z "$password" ]]; then
        print_error "Password cannot be empty"
        exit 1
    fi
    
    store_in_keychain "$username" "$password"
    
    echo ""
    print_success "Credentials stored in macOS Keychain"
    echo ""
    echo "You can now run collectors without passing credentials:"
    echo "  python collectors/esf_collector.py --output elasticsearch"
    echo ""
}

# Create/update .env file securely
create_env_file() {
    local password="$1"
    
    # Create .env with restricted permissions
    # Using a temp file to set permissions before writing sensitive data
    local temp_file=$(mktemp)
    chmod 600 "$temp_file"

    if [[ -f "$ENV_FILE" ]]; then
        # Only the password changes: keep the Kibana keys and Splunk settings docker-compose.yml reads
        grep -v '^ELASTIC_PASSWORD=' "$ENV_FILE" > "$temp_file" || true
    else
        cat > "$temp_file" << EOF
# coreSigma Docker Environment
# Generated by setup_credentials.sh
# This file contains secrets - NEVER commit to version control!
#
# To regenerate: ./scripts/setup_credentials.sh --sync-docker

# Kibana encryption keys (docker-compose.yml reads them from here)
KIBANA_ENCRYPTION_KEY='$(openssl rand -base64 32)'
KIBANA_SECURITY_KEY='$(openssl rand -base64 32)'
KIBANA_REPORTING_KEY='$(openssl rand -base64 32)'
EOF
    fi
    # Single-quoted: taken literally by both docker compose and `source` (bench_up.sh)
    printf "ELASTIC_PASSWORD='%s'\n" "$password" >> "$temp_file"

    mv "$temp_file" "$ENV_FILE"
    print_success "Created $ENV_FILE with secure permissions (600)"
}

# Sync password to both Docker (.env) and Keychain
sync_docker_password() {
    echo ""
    echo "Setting up password for Docker and collectors..."
    echo ""
    print_info "This will:"
    echo "  1. Store password in macOS Keychain (for collectors)"
    echo "  2. Create .env file (for Docker Compose)"
    echo ""
    
    read -r -p "Username [elastic]: " username
    username="${username:-elastic}"
    
    read -r -sp "Enter new password: " password
    echo ""
    read -r -sp "Confirm password: " password_confirm
    echo ""
    
    if [[ -z "$password" ]]; then
        print_error "Password cannot be empty"
        exit 1
    fi
    
    if [[ "$password" != "$password_confirm" ]]; then
        print_error "Passwords do not match"
        exit 1
    fi
    
    # Check password strength (basic check)
    if [[ ${#password} -lt 8 ]]; then
        print_error "Password must be at least 8 characters"
        exit 1
    fi

    # .env single-quotes it, and a single-quoted value cannot hold a '
    if [[ "$password" == *"'"* ]]; then
        print_error "Password cannot contain a single quote (')"
        exit 1
    fi
    
    # Store in Keychain
    store_in_keychain "$username" "$password"
    
    # Create .env file
    create_env_file "$password"
    
    echo ""
    print_success "Password configured for both Docker and collectors"
    echo ""
    
    # Check if Docker is running
    if docker ps &>/dev/null; then
        echo "Docker is running. To apply the new password:"
        echo ""
        echo "  ${YELLOW}docker-compose down && docker-compose up -d${NC}"
        echo ""
        read -r -p "Restart Docker now? [y/N]: " restart_docker
        if [[ "$restart_docker" =~ ^[Yy]$ ]]; then
            echo ""
            echo "Restarting Docker services..."
            cd "$PROJECT_DIR"
            docker-compose down
            docker-compose up -d
            echo ""
            print_success "Docker services restarted with new password"
        fi
    else
        echo "Start Docker with:"
        echo "  cd $PROJECT_DIR && docker-compose up -d"
    fi
    
    echo ""
    echo "Test authentication with:"
    echo "  ./scripts/setup_credentials.sh --test"
    echo ""
}

# Create API key
create_api_key() {
    echo ""
    echo "Creating Elasticsearch API key..."
    echo ""
    
    # Need existing credentials first
    local auth_header=""
    
    # Try keychain first
    if password=$(security find-generic-password -s "$KEYCHAIN_SERVICE" -a "elastic" -w 2>/dev/null); then
        auth_header="elastic:$password"
    elif [[ -n "$ES_USER" && -n "$ES_PASSWORD" ]]; then
        auth_header="$ES_USER:$ES_PASSWORD"
    else
        echo "Need existing credentials to create API key."
        read -r -p "Username [elastic]: " username
        username="${username:-elastic}"
        read -r -sp "Password: " password
        echo ""
        auth_header="$username:$password"
    fi
    
    # Create API key with limited permissions. Basic auth goes to curl as a header on stdin (-H @-):
    # with -u the password would be on curl's argv, which `ps` shows
    response=$(printf 'Authorization: Basic %s\n' "$(printf '%s' "$auth_header" | base64 | tr -d '\n')" |
        curl -s -X POST "$ES_URL/_security/api_key" \
        -H "Content-Type: application/json" \
        -H @- \
        -d '{
            "name": "coresigma-collector",
            "role_descriptors": {
                "coresigma_writer": {
                    "cluster": ["monitor"],
                    "index": [
                        {
                            "names": ["macos-telemetry-*", "macos-esf-*", "macos-ul-*"],
                            "privileges": ["write", "create_index", "auto_configure"]
                        }
                    ]
                }
            },
            "expiration": "365d"
        }')
    
    # Check for error
    if echo "$response" | grep -q '"error"'; then
        print_error "Failed to create API key:"
        echo "$response" | python3 -m json.tool 2>/dev/null || echo "$response"
        exit 1
    fi
    
    # Extract encoded key
    encoded=$(echo "$response" | python3 -c "import sys, json; d=json.load(sys.stdin); print(d['encoded'])" 2>/dev/null)
    
    if [[ -z "$encoded" ]]; then
        print_error "Failed to parse API key response"
        echo "$response"
        exit 1
    fi
    
    print_success "API key created successfully"
    echo ""
    echo "Add this to your shell profile (~/.zshrc or ~/.bash_profile):"
    echo ""
    echo -e "  ${GREEN}export ES_API_KEY=\"$encoded\"${NC}"
    echo ""
    echo "Or create ~/.coresigma/config.yml:"
    echo ""
    echo "  elasticsearch:"
    echo "    api_key: \"$encoded\""
    echo ""
    
    # Offer to store in config
    read -r -p "Create config file now? [y/N]: " create_config
    if [[ "$create_config" =~ ^[Yy]$ ]]; then
        mkdir -p -m 700 "$HOME/.coresigma"
        (umask 077 && cat > "$HOME/.coresigma/config.yml") << EOF
# coreSigma Configuration
elasticsearch:
  url: $ES_URL
  api_key: "$encoded"
EOF
        chmod 600 "$HOME/.coresigma/config.yml"
        print_success "Created ~/.coresigma/config.yml"
    fi
}

# Test authentication
test_auth() {
    echo ""
    echo "Testing Elasticsearch authentication..."
    echo ""
    
    cd "$(dirname "$0")/.."
    
    if [[ -d "venv" ]]; then
        source venv/bin/activate
    fi
    
    python3 -c "
import os
from collectors.auth import get_elasticsearch_auth, cluster_info, AuthenticationError

try:
    api_key, basic_auth = get_elasticsearch_auth()
    if api_key:
        print('✓ Using API key authentication')
    elif basic_auth:
        print(f'✓ Using basic auth (user: {basic_auth[0]})')
    
    info = cluster_info(os.environ.get('ES_URL', 'http://localhost:9200'))
    print(f'✓ Connected to cluster: {info[\"cluster_name\"]}')
    print(f'✓ Elasticsearch version: {info[\"version\"][\"number\"]}')
    print()
    print('Authentication working!')
except AuthenticationError as e:
    print(f'✗ {e}')
    exit(1)
except Exception as e:
    print(f'✗ Connection failed: {e}')
    exit(1)
"
}

# Show help
show_help() {
    echo "Usage: $0 [OPTION]"
    echo ""
    echo "Options:"
    echo "  --sync-docker Set password for Docker AND Keychain (recommended for local setup)"
    echo "  --password    Store username/password in macOS Keychain only"
    echo "  --api-key     Create a limited-scope API key (recommended for production)"
    echo "  --test        Test current authentication configuration"
    echo "  --help        Show this help message"
    echo ""
    echo "For Local Docker Setup:"
    echo "  Run: $0 --sync-docker"
    echo "  This creates both .env (for Docker) and Keychain entry (for collectors)"
    echo ""
    echo "Authentication Priority (highest to lowest):"
    echo "  1. ES_API_KEY environment variable"
    echo "  2. macOS Keychain"
    echo "  3. ES_USER/ES_PASSWORD environment variables"
    echo "  4. ~/.coresigma/config.yml"
    echo ""
}

# Main
print_header

case "${1:-}" in
    --sync-docker)
        sync_docker_password
        ;;
    --api-key)
        create_api_key
        ;;
    --test)
        test_auth
        ;;
    --help|-h)
        show_help
        ;;
    --password)
        if check_existing; then
            echo ""
            read -r -p "Credentials exist. Overwrite? [y/N]: " overwrite
            if [[ ! "$overwrite" =~ ^[Yy]$ ]]; then
                echo "Keeping existing credentials."
                exit 0
            fi
        fi
        setup_password
        ;;
    *)
        # Default: show help for new users, prompt existing users
        if check_existing; then
            echo ""
            echo "Choose an action:"
            echo "  1) Update password for Docker + collectors (--sync-docker)"
            echo "  2) Update Keychain only (--password)"
            echo "  3) Test current authentication (--test)"
            echo "  4) Show help (--help)"
            echo ""
            read -r -p "Selection [1]: " selection
            selection="${selection:-1}"
            case "$selection" in
                1) sync_docker_password ;;
                2) setup_password ;;
                3) test_auth ;;
                4) show_help ;;
                *) echo "Invalid selection"; exit 1 ;;
            esac
        else
            echo "No credentials configured. Setting up for Docker + collectors..."
            sync_docker_password
        fi
        ;;
esac
